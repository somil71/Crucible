//! Determinism Auditor & Differential Bisect Engine for Crucible.
//!
//! Provides automated bisection to locate the EXACT instruction step, instruction pointer,
//! and memory byte or CPU register bitflip where two executions or perturbed states diverge.

use crate::cpu::CpuRegisters;
use crate::interp::{Emulator, EmulatorSnapshot};
use crate::memory::VirtualMemory;

/// Categorization of the exact hardware or state divergence detected.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DivergenceTarget {
    Register {
        name: &'static str,
        expected: u64,
        actual: u64,
        differing_bits: u64,
        first_diff_bit: usize,
    },
    Memory {
        addr: u64,
        expected: u8,
        actual: u8,
        differing_bits: u8,
        first_diff_bit: usize,
    },
    InstructionPointer {
        expected_rip: u64,
        actual_rip: u64,
    },
    InstructionCount {
        expected: u64,
        actual: u64,
    },
    ThreadOrder {
        expected_thread_idx: usize,
        actual_thread_idx: usize,
    },
    HaltedMismatch {
        expected_halted: bool,
        actual_halted: bool,
    },
}

/// Detailed report generated by the Determinism Auditor when two runs diverge.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DivergenceReport {
    pub step_index: u64,
    pub rip: u64,
    pub mnemonic: Option<String>,
    pub target: DivergenceTarget,
    pub description: String,
}

pub struct DeterminismAuditor;

impl DeterminismAuditor {
    /// Compares CPU registers between expected and actual execution states.
    pub fn compare_registers(r1: &CpuRegisters, r2: &CpuRegisters) -> Option<DivergenceTarget> {
        let pairs: [(&'static str, u64, u64); 17] = [
            ("rax", r1.rax, r2.rax),
            ("rbx", r1.rbx, r2.rbx),
            ("rcx", r1.rcx, r2.rcx),
            ("rdx", r1.rdx, r2.rdx),
            ("rsi", r1.rsi, r2.rsi),
            ("rdi", r1.rdi, r2.rdi),
            ("rbp", r1.rbp, r2.rbp),
            ("rsp", r1.rsp, r2.rsp),
            ("r8", r1.r8, r2.r8),
            ("r9", r1.r9, r2.r9),
            ("r10", r1.r10, r2.r10),
            ("r11", r1.r11, r2.r11),
            ("r12", r1.r12, r2.r12),
            ("r13", r1.r13, r2.r13),
            ("r14", r1.r14, r2.r14),
            ("r15", r1.r15, r2.r15),
            ("rflags", r1.rflags, r2.rflags),
        ];

        for (name, expected, actual) in pairs {
            if expected != actual {
                let differing_bits = expected ^ actual;
                let first_diff_bit = differing_bits.trailing_zeros() as usize;
                return Some(DivergenceTarget::Register {
                    name,
                    expected,
                    actual,
                    differing_bits,
                    first_diff_bit,
                });
            }
        }
        None
    }

    /// Compares two virtual memories and returns the first differing memory byte, if any.
    pub fn compare_memory(m1: &VirtualMemory, m2: &VirtualMemory) -> Option<DivergenceTarget> {
        let mut all_pages: Vec<u64> = m1.pages.keys().chain(m2.pages.keys()).copied().collect();
        all_pages.sort();
        all_pages.dedup();

        for base in all_pages {
            let p1 = m1.pages.get(&base);
            let p2 = m2.pages.get(&base);
            match (p1, p2) {
                (Some(s1), Some(s2)) => {
                    if s1.as_slice() != s2.as_slice() {
                        for offset in 0..crate::memory::PAGE_SIZE {
                            let b1 = s1[offset];
                            let b2 = s2[offset];
                            if b1 != b2 {
                                let addr = base + offset as u64;
                                let diff = b1 ^ b2;
                                return Some(DivergenceTarget::Memory {
                                    addr,
                                    expected: b1,
                                    actual: b2,
                                    differing_bits: diff,
                                    first_diff_bit: diff.trailing_zeros() as usize,
                                });
                            }
                        }
                    }
                }
                (Some(s1), None) => {
                    for offset in 0..crate::memory::PAGE_SIZE {
                        if s1[offset] != 0 {
                            let addr = base + offset as u64;
                            let diff = s1[offset];
                            return Some(DivergenceTarget::Memory {
                                addr,
                                expected: s1[offset],
                                actual: 0,
                                differing_bits: diff,
                                first_diff_bit: diff.trailing_zeros() as usize,
                            });
                        }
                    }
                }
                (None, Some(s2)) => {
                    for offset in 0..crate::memory::PAGE_SIZE {
                        if s2[offset] != 0 {
                            let addr = base + offset as u64;
                            let diff = s2[offset];
                            return Some(DivergenceTarget::Memory {
                                addr,
                                expected: 0,
                                actual: s2[offset],
                                differing_bits: diff,
                                first_diff_bit: diff.trailing_zeros() as usize,
                            });
                        }
                    }
                }
                (None, None) => {}
            }
        }
        None
    }

    /// Compares two emulator snapshots and identifies the first divergence.
    pub fn diff_snapshots(expected: &EmulatorSnapshot, actual: &EmulatorSnapshot) -> Option<DivergenceTarget> {
        if expected.cpu.regs.rip != actual.cpu.regs.rip {
            return Some(DivergenceTarget::InstructionPointer {
                expected_rip: expected.cpu.regs.rip,
                actual_rip: actual.cpu.regs.rip,
            });
        }

        if let Some(reg_diff) = Self::compare_registers(&expected.cpu.regs, &actual.cpu.regs) {
            return Some(reg_diff);
        }

        if expected.current_thread_idx != actual.current_thread_idx {
            return Some(DivergenceTarget::ThreadOrder {
                expected_thread_idx: expected.current_thread_idx,
                actual_thread_idx: actual.current_thread_idx,
            });
        }

        if expected.cpu.halted != actual.cpu.halted {
            return Some(DivergenceTarget::HaltedMismatch {
                expected_halted: expected.cpu.halted,
                actual_halted: actual.cpu.halted,
            });
        }

        None
    }

    /// Bisects execution between a baseline emulator and a candidate emulator to locate
    /// the EXACT single instruction step where divergence first occurred.
    pub fn bisect_divergence(
        mut baseline: Emulator,
        mut candidate: Emulator,
        max_steps: u64,
    ) -> Option<DivergenceReport> {
        let mut step = 0u64;

        while step < max_steps {
            // Check pre-step state divergence
            if baseline.cpu.regs.rip != candidate.cpu.regs.rip {
                return Some(DivergenceReport {
                    step_index: step,
                    rip: baseline.cpu.regs.rip,
                    mnemonic: None,
                    target: DivergenceTarget::InstructionPointer {
                        expected_rip: baseline.cpu.regs.rip,
                        actual_rip: candidate.cpu.regs.rip,
                    },
                    description: format!(
                        "RIP divergence at step {}: expected {:#x}, got {:#x}",
                        step, baseline.cpu.regs.rip, candidate.cpu.regs.rip
                    ),
                });
            }

            if let Some(target) = Self::compare_registers(&baseline.cpu.regs, &candidate.cpu.regs) {
                return Some(DivergenceReport {
                    step_index: step,
                    rip: baseline.cpu.regs.rip,
                    mnemonic: None,
                    target,
                    description: format!("Register divergence at step {} (RIP {:#x})", step, baseline.cpu.regs.rip),
                });
            }

            // Step both emulators
            let b_ok = baseline.step();
            let c_ok = candidate.step();

            step += 1;

            match (b_ok, c_ok) {
                (Ok(true), Ok(true)) => {
                    // Check post-step registers
                    if let Some(target) = Self::compare_registers(&baseline.cpu.regs, &candidate.cpu.regs) {
                        let m = baseline.trace_log.last().map(|e| format!("{:?}", e.mnemonic));
                        return Some(DivergenceReport {
                            step_index: step,
                            rip: baseline.cpu.regs.rip,
                            mnemonic: m,
                            target,
                            description: format!("Instruction execution produced register divergence at step {}", step),
                        });
                    }

                    // Check post-step memory if dirty pages exist
                    if baseline.mem.dirty_pages_count() > 0 || candidate.mem.dirty_pages_count() > 0 {
                        if let Some(target) = Self::compare_memory(&baseline.mem, &candidate.mem) {
                            let m = baseline.trace_log.last().map(|e| format!("{:?}", e.mnemonic));
                            return Some(DivergenceReport {
                                step_index: step,
                                rip: baseline.cpu.regs.rip,
                                mnemonic: m,
                                target,
                                description: format!("Memory divergence at step {}", step),
                            });
                        }
                    }
                }
                (Ok(false), Ok(false)) => {
                    // Both finished normally without divergence
                    break;
                }
                (b_res, c_res) => {
                    return Some(DivergenceReport {
                        step_index: step,
                        rip: baseline.cpu.regs.rip,
                        mnemonic: None,
                        target: DivergenceTarget::HaltedMismatch {
                            expected_halted: baseline.cpu.halted,
                            actual_halted: candidate.cpu.halted,
                        },
                        description: format!(
                            "Execution flow divergence at step {}: baseline {:?}, candidate {:?}",
                            step, b_res, c_res
                        ),
                    });
                }
            }
        }

        None
    }

    /// Evaluates an intentional single-bit injection and confirms the auditor detects it.
    pub fn audit_injection<F>(
        base_emu: &Emulator,
        inject_fn: F,
        max_steps: u64,
    ) -> Option<DivergenceReport>
    where
        F: FnOnce(&mut Emulator),
    {
        let baseline = base_emu.fork();
        let mut candidate = base_emu.fork();

        // Inject the perturbation into candidate
        inject_fn(&mut candidate);

        Self::bisect_divergence(baseline, candidate, max_steps)
    }
}
